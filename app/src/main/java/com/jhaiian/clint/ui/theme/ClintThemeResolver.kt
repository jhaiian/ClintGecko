            )
            "material_you" -> {
                val s = dynamicScheme(context, isLight)
                val pct = 0.16f
                base.copy(
                    surface = lerp(s.surfaceContainer, s.primary, pct),
                    background = lerp(base.background, s.primary, pct),
                    statusBar = lerp(s.surfaceContainer, s.primary, pct),
                    navigationBar = lerp(s.surfaceContainer, s.primary, pct),
                    addressBar = lerp(s.surfaceContainerHighest, s.primary, pct + 0.04f),
                    popupBackground = lerp(base.popupBackground, s.primary, pct),
                    cardBackground = lerp(base.cardBackground, s.primary, pct)
                )
            }
            else -> base
        }
        else -> base
    }
}

internal fun resolveClintTheme(context: Context, theme: String, accent: String, intensity: String): ClintResolvedTheme {
    val isLight = ThemeMode.isLight(theme)
    val base = if (accent == "material_you") materialYouBase(context, isLight) else accentBase(isLight, accent)
    return applySurfaceIntensity(base, context, accent, intensity, isLight)
}
